"""Self-test for comment_guard.py: python test_comment_guard.py"""

import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import comment_guard as cg


def bodies(text, language):
    return [b.strip() for _, b in cg.offenders(text, language)]


class Offenders(unittest.TestCase):
    def test_al_doc_comment_allowed_inline_comment_denied(self):
        text = (
            "/// <summary>Posts the order.</summary>\n"
            "procedure Post()\n"
            "begin\n"
            "    // loop through lines\n"
            "    Message('http://x // not a comment');\n"
            "    /* old code */\n"
            "end;\n")
        self.assertEqual(bodies(text, "al"), ["// loop through lines", "/* old code */"])

    def test_al_test_markers_only_in_test_codeunits(self):
        body = "    // [GIVEN] A released order\n    // because it is faster\n"
        test = "codeunit 50100 X\n{\n    Subtype = Test;\n" + body + "}\n"
        self.assertEqual(bodies(test, "al"), ["// because it is faster"])
        self.assertEqual(bodies("codeunit 50100 X\n{\n" + body + "}\n", "al"),
                         ["// [GIVEN] A released order", "// because it is faster"])

    def test_al_quoted_identifier_is_not_a_comment(self):
        self.assertEqual(bodies('Rec."Sell-to // No." := 1;\n', "al"), [])

    def test_cs_doc_and_directives(self):
        text = (
            "/// <summary>Id.</summary>\n"
            "/** <summary>x</summary> */\n"
            "// ReSharper disable once UnusedMember.Global\n"
            "var url = \"https://a//b\"; // trailing note\n"
            "var path = @\"C:\\\\x\"\"//y\";\n"
            "/* block */\n")
        self.assertEqual(bodies(text, "cs"), ["// trailing note", "/* block */"])

    def test_cs_auto_generated_skipped(self):
        self.assertEqual(bodies("// <auto-generated/>\n// note\n", "cs"), [])

    def test_razor(self):
        text = (
            "<a href=\"https://x\">link</a>\n"
            "<p>It's fine</p>\n"
            "@* razor note *@\n"
            "<!-- html note -->\n"
            "@code {\n    // code note\n}\n")
        self.assertEqual(bodies(text, "razor"), ["@* razor note *@", "<!-- html note -->", "// code note"])

    def test_sql(self):
        text = "SELECT '--x' AS A -- why\n/* block */\nFROM T;\n"
        self.assertEqual(bodies(text, "sql"), ["-- why", "/* block */"])

    def test_js_template_literal(self):
        text = "const a = `x // y\n z`; // note\n/** doc */\n"
        self.assertEqual(bodies(text, "js"), ["// note"])

    def test_cal_markers_and_code_allowed_prose_denied(self):
        text = (
            "OBJECT Codeunit 50000 X\n"
            "    // START DSC 1234 2026-11-26\n"
            "    //INGEST\n"
            "    //Cust.GET(\"No.\");\n"
            "    //IF Amount > 0 THEN\n"
            "    // calcola il totale prima della registrazione\n"
            "    // END DSC 1234\n")
        self.assertEqual(bodies(text, "cal"), ["// calcola il totale prima della registrazione"])

    def test_language_of(self):
        self.assertEqual(cg.language_of("src/A.al"), "al")
        self.assertIsNone(cg.language_of("app/obj/Debug/X.cs"))
        self.assertIsNone(cg.language_of("notes.txt", "hello"))
        self.assertEqual(cg.language_of("CU50000.txt", "OBJECT Codeunit 50000 X\n"), "cal")
        self.assertIsNone(cg.language_of("README.md"))


class Hook(unittest.TestCase):
    def run_hook(self, event):
        result = subprocess.run(
            [sys.executable, os.path.join(HERE, "comment_guard.py"), "hook"],
            input=json.dumps(event).encode(), capture_output=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.decode().strip()

    def test_edit_adding_comment_denied(self):
        with tempfile.TemporaryDirectory() as folder:
            path = os.path.join(folder, "A.al")
            with open(path, "w") as handle:
                handle.write("procedure A()\nbegin\n    X := 1;\nend;\n")
            out = self.run_hook({"tool_name": "Edit", "tool_input": {
                "file_path": path, "old_string": "    X := 1;", "new_string": "    // set X\n    X := 1;"}})
            self.assertIn('"deny"', out)
            self.assertIn("set X", out)

    def test_edit_keeping_existing_comment_allowed(self):
        with tempfile.TemporaryDirectory() as folder:
            path = os.path.join(folder, "A.al")
            with open(path, "w") as handle:
                handle.write("procedure A()\nbegin\n    // legacy\n    X := 1;\nend;\n")
            out = self.run_hook({"tool_name": "Edit", "tool_input": {
                "file_path": path, "old_string": "X := 1;", "new_string": "X := 2;"}})
            self.assertEqual(out, "")

    def test_write_doc_comment_allowed(self):
        with tempfile.TemporaryDirectory() as folder:
            out = self.run_hook({"tool_name": "Write", "tool_input": {
                "file_path": os.path.join(folder, "B.cs"),
                "content": "/// <summary>B.</summary>\npublic class B { }\n"}})
            self.assertEqual(out, "")

    def test_non_code_file_ignored(self):
        out = self.run_hook({"tool_name": "Write", "tool_input": {
            "file_path": "README.md", "content": "// anything"}})
        self.assertEqual(out, "")

    def test_kill_switch(self):
        env = dict(os.environ, DSC_COMMENT_GUARD_DISABLE="1")
        result = subprocess.run(
            [sys.executable, os.path.join(HERE, "comment_guard.py"), "hook"],
            input=json.dumps({"tool_name": "Write", "tool_input": {
                "file_path": "x.al", "content": "// note\n"}}).encode(),
            capture_output=True, env=env)
        self.assertEqual(result.stdout.decode().strip(), "")


if __name__ == "__main__":
    unittest.main()
