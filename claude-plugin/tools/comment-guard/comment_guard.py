#!/usr/bin/env python3
"""DSC comment guard: code carries no comments except documentation comments.

Allowed everywhere: documentation comments on objects, procedures, types and members
(AL and C# ``///``, JSDoc/C# ``/** */``), and tool directives (``eslint-disable``,
``@ts-expect-error``, ``ReSharper disable``, ``prettier-ignore``, ``language=``).
Allowed in AL test codeunits: ``// [FEATURE]``, ``// [SCENARIO]``, ``// [GIVEN]``,
``// [WHEN]``, ``// [THEN]``.
Allowed in C/AL: customization markers (``// START DSC 1234``, ``//INGEST``) and
commented-out code lines.

Usage:
    comment_guard.py hook            PreToolUse hook: reads the tool call JSON on stdin and
                                     denies a Write/Edit that adds a forbidden comment.
    comment_guard.py scan PATH...    lists forbidden comments in files or folders.
    comment_guard.py scan-md PATH... same, inside fenced code blocks of Markdown files.
    Add --json to either scan for machine-readable output.

Kill switch: DSC_COMMENT_GUARD_DISABLE=1 (hook only).
"""

import json
import os
import re
import sys
from collections import Counter

EXTENSIONS = {
    ".al": "al",
    ".cs": "cs",
    ".razor": "razor",
    ".cshtml": "razor",
    ".js": "js",
    ".mjs": "js",
    ".cjs": "js",
    ".ts": "js",
    ".tsx": "js",
    ".jsx": "js",
    ".css": "css",
    ".scss": "css",
    ".sql": "sql",
    ".cal": "cal",
    ".txt": "cal",
}

FENCE_LANGUAGES = {
    "al": "al",
    "cs": "cs",
    "csharp": "cs",
    "c#": "cs",
    "razor": "razor",
    "cshtml": "razor",
    "html": "razor",
    "js": "js",
    "javascript": "js",
    "ts": "js",
    "typescript": "js",
    "css": "css",
    "scss": "css",
    "sql": "sql",
    "tsql": "sql",
    "cal": "cal",
    "c/al": "cal",
}

SKIPPED_PATH_PARTS = (
    "/obj/", "/bin/", "/node_modules/", "/.alpackages/", "/.git/", "/wwwroot/lib/",
    "/migrations/", "/.vs/", "/.claude/", "/translations/",
)
SKIPPED_SUFFIXES = (".g.cs", ".designer.cs", ".min.js", ".min.css", ".d.ts")

CAL_OBJECT_HEADER = re.compile(
    r"^OBJECT (Table|Page|Form|Codeunit|Report|Dataport|XMLport|Query|MenuSuite) \d+", re.M)
AL_TEST_CODEUNIT = re.compile(r"Subtype\s*=\s*Test\b|\[Test\]", re.I)
AL_TEST_MARKER = re.compile(r"^//\s*\[(FEATURE|SCENARIO|GIVEN|WHEN|THEN)\b", re.I)
TOOL_DIRECTIVE = re.compile(
    r"^(//|/\*)\s*(eslint-|@ts-|prettier-ignore|ReSharper |resharper |NOSONAR|language=|"
    r"istanbul |c8 |<auto-generated|#region|#endregion|stylelint-|sourceMappingURL)")
CAL_MARKER = re.compile(
    r"^//[-<>=*#+\s]*(START|END|BEGIN|STOP|INIZIO|FINE|BEG|ENDE)\b"
    r"|^//[-<>=*#+\s]*[A-Z][A-Z0-9]+([-_./][A-Z0-9]+)*(\s|$|[-_.:/<>])")
CAL_KEYWORDS = re.compile(
    r"^//\s*(IF|THEN|ELSE|BEGIN|END|CASE|OF|REPEAT|UNTIL|EXIT|WITH|DO|WHILE|FOR|TO|"
    r"DOWNTO|ERROR|MESSAGE|CONFIRM|SETRANGE|SETFILTER|FIND|FINDFIRST|FINDSET|FINDLAST|"
    r"GET|INSERT|MODIFY|DELETE|VALIDATE|CALCFIELDS|TESTFIELD|INIT|RESET|NEXT|COMMIT)\b", re.I)


class Syntax:
    def __init__(self, line, blocks, quotes, backslash_escape, multiline_quotes=()):
        self.line = line
        self.blocks = blocks
        self.quotes = quotes
        self.backslash_escape = backslash_escape
        self.multiline_quotes = multiline_quotes


SYNTAX = {
    "al": Syntax(["//"], [("/*", "*/")], ["'", '"'], False),
    "cal": Syntax(["//"], [], ["'", '"'], False),
    "sql": Syntax(["--"], [("/*", "*/")], ["'"], False),
    "cs": Syntax(["//"], [("/*", "*/")], ['"', "'"], True),
    "razor": Syntax(["//"], [("@*", "*@"), ("<!--", "-->"), ("/*", "*/")], ['"', "'"], True),
    "js": Syntax(["//"], [("/*", "*/")], ['"', "'"], True, ["`"]),
    "css": Syntax([], [("/*", "*/")], ['"', "'"], True),
}


def language_of(path, text=None):
    lowered = path.replace("\\", "/").lower()
    if any(part in "/" + lowered for part in SKIPPED_PATH_PARTS):
        return None
    if lowered.endswith(SKIPPED_SUFFIXES):
        return None
    language = EXTENSIONS.get(os.path.splitext(lowered)[1])
    if language == "cal" and lowered.endswith(".txt"):
        if text is None or not CAL_OBJECT_HEADER.search(text):
            return None
    return language


def _skip_string(text, i, quote, syntax):
    if quote == '"' and syntax.backslash_escape and i > 0 and text[i - 1] == "@":
        return _skip_doubled(text, i + 1, quote, multiline=True)
    if text.startswith('"""', i) and syntax.backslash_escape:
        end = text.find('"""', i + 3)
        return len(text) if end < 0 else end + 3
    multiline = quote in syntax.multiline_quotes
    if not syntax.backslash_escape:
        return _skip_doubled(text, i + 1, quote, multiline)
    j = i + 1
    while j < len(text):
        c = text[j]
        if c == "\\":
            j += 2
            continue
        if c == quote:
            return j + 1
        if c == "\n" and not multiline:
            return j
        j += 1
    return j


def _skip_doubled(text, j, quote, multiline):
    while j < len(text):
        c = text[j]
        if c == quote:
            if text.startswith(quote * 2, j):
                j += 2
                continue
            return j + 1
        if c == "\n" and not multiline:
            return j
        j += 1
    return j


def comments(text, language):
    """Yields (line number, comment text) for every comment in ``text``."""
    syntax = SYNTAX[language]
    quotes = list(syntax.quotes) + list(syntax.multiline_quotes)
    i, line, n = 0, 1, len(text)
    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
            i += 1
            continue
        opener = next((b for b in syntax.blocks if text.startswith(b[0], i)), None)
        if opener:
            end = text.find(opener[1], i + len(opener[0]))
            end = n if end < 0 else end + len(opener[1])
            body = text[i:end]
            yield line, body
            line += body.count("\n")
            i = end
            continue
        prefix = next((p for p in syntax.line if text.startswith(p, i)), None)
        if prefix and not (prefix == "//" and i > 0 and text[i - 1] == ":"):
            end = text.find("\n", i)
            end = n if end < 0 else end
            yield line, text[i:end].rstrip("\r")
            i = end
            continue
        if c in quotes:
            end = _skip_string(text, i, c, syntax)
            line += text.count("\n", i, end)
            i = end
            continue
        i += 1


def allowed(comment, language, is_test):
    stripped = comment.strip()
    if TOOL_DIRECTIVE.match(stripped):
        return True
    if language in ("al", "cs", "razor", "js") and stripped.startswith("///"):
        return True
    if language in ("cs", "razor", "js") and stripped.startswith("/**") and not stripped.startswith("/**/"):
        return True
    if language == "al" and is_test and AL_TEST_MARKER.match(stripped):
        return True
    if language == "cal":
        return bool(CAL_MARKER.match(stripped) or CAL_KEYWORDS.match(stripped)
                    or ":=" in stripped or stripped.rstrip().endswith(";")
                    or re.match(r"^//\s*$", stripped))
    return False


def offenders(text, language, is_test=None):
    if is_test is None:
        is_test = language == "al" and bool(AL_TEST_CODEUNIT.search(text))
    if language == "cs" and "<auto-generated" in text:
        return []
    return [(ln, body) for ln, body in comments(text, language) if not allowed(body, language, is_test)]


def _normalized(body):
    return re.sub(r"\s+", " ", body).strip()


def added_offenders(old_text, new_text, language, is_test):
    before = Counter(_normalized(b) for _, b in offenders(old_text, language, is_test))
    result = []
    for ln, body in offenders(new_text, language, is_test):
        key = _normalized(body)
        if before[key] > 0:
            before[key] -= 1
            continue
        result.append((ln, body))
    return result


EXCEPTIONS = {
    "al": " In test codeunits the // [GIVEN] / [WHEN] / [THEN] / [SCENARIO] / [FEATURE] lines are allowed.",
    "cal": " In C/AL the change markers (// START DSC <ticket>, // END DSC) and commented-out standard code inside a marker block are allowed; prose is not.",
}


def deny_reason(found, language, path):
    shown = "; ".join(f"line {ln}: {_normalized(body)[:100]}" for ln, body in found[:5])
    more = f" (+{len(found) - 5} more)" if len(found) > 5 else ""
    return (
        f"DSC hard rule -- no comments in code. This edit to {os.path.basename(path)} adds "
        f"{len(found)} forbidden comment(s): {shown}{more}. "
        "Only documentation comments are allowed: /// (AL, C#) or /** */ (C#, JS) on objects, "
        "procedures, types and members." + EXCEPTIONS.get(language, "") + " "
        "If you feel you must explain a choice, either you do not fully believe it is the best "
        "one -- then pick the option that needs no defence, or ask the user -- or the text is "
        "documentation -- then it goes into the doc comment or the docs, not the body. Make the "
        "code explain itself: a clearer name, an extracted procedure, a named constant or label. "
        "Commented-out code is deleted, never kept (C/AL standard code excepted). "
        "Redo this edit without those comments; do not try to bypass this guard."
    )


def _read(path):
    try:
        with open(path, encoding="utf-8-sig", errors="replace", newline="") as handle:
            return handle.read()
    except OSError:
        return None


def hook():
    if os.environ.get("DSC_COMMENT_GUARD_DISABLE") == "1":
        return 0
    try:
        event = json.loads(sys.stdin.buffer.read().decode("utf-8", errors="replace") or "{}")
    except ValueError:
        return 0
    tool = event.get("tool_name", "")
    params = event.get("tool_input") or {}
    path = params.get("file_path") or ""
    if tool not in ("Write", "Edit") or not path:
        return 0
    current = _read(path) or ""
    if tool == "Write":
        old_text, new_text = current, params.get("content") or ""
    else:
        old_string = params.get("old_string") or ""
        new_string = params.get("new_string") or ""
        if old_string and old_string in current:
            old_text = current
            if params.get("replace_all"):
                new_text = current.replace(old_string, new_string)
            else:
                new_text = current.replace(old_string, new_string, 1)
        else:
            old_text, new_text = old_string, new_string
    language = language_of(path, new_text or current)
    if not language:
        return 0
    is_test = language == "al" and bool(AL_TEST_CODEUNIT.search(new_text or current))
    found = added_offenders(old_text, new_text, language, is_test)
    if not found:
        return 0
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": "deny",
        "permissionDecisionReason": deny_reason(found, language, path),
    }}))
    return 0


def _walk(paths):
    for root in paths:
        if os.path.isfile(root):
            yield root
            continue
        for folder, dirs, files in os.walk(root):
            dirs[:] = [d for d in dirs if d.lower() not in
                       ("obj", "bin", "node_modules", ".alpackages", ".git", ".vs", ".claude")]
            for name in files:
                yield os.path.join(folder, name)


def scan(paths):
    for path in _walk(paths):
        if not language_of(path, ""):
            if not path.lower().endswith(".txt"):
                continue
        text = _read(path)
        if text is None:
            continue
        language = language_of(path, text)
        if not language:
            continue
        for ln, body in offenders(text, language):
            yield path, ln, body


FENCE = re.compile(r"^(\s*)(```+|~~~+)\s*([^\s`]*)[^\n]*\n(.*?)^\1\2\s*$", re.M | re.S)


def scan_md(paths):
    for path in _walk(paths):
        if not path.lower().endswith(".md"):
            continue
        text = _read(path)
        if text is None:
            continue
        for match in FENCE.finditer(text):
            language = FENCE_LANGUAGES.get(match.group(3).lower())
            if not language:
                continue
            first_line = text.count("\n", 0, match.start(4)) + 1
            for ln, body in offenders(match.group(4), language):
                yield path, first_line + ln - 1, body


def report(rows, as_json):
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    rows = list(rows)
    if as_json:
        print(json.dumps([{"file": p, "line": ln, "comment": b} for p, ln, b in rows], indent=1))
    else:
        for p, ln, b in rows:
            print(f"{p}:{ln}: {_normalized(b)[:160]}")
        files = len({p for p, _, _ in rows})
        print(f"{len(rows)} forbidden comment(s) in {files} file(s)", file=sys.stderr)
    return 1 if rows else 0


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    command, rest = argv[1], argv[2:]
    as_json = "--json" in rest
    rest = [a for a in rest if a != "--json"] or ["."]
    if command == "hook":
        return hook()
    if command == "scan":
        return report(scan(rest), as_json)
    if command == "scan-md":
        return report(scan_md(rest), as_json)
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
